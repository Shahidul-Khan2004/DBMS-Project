function convertTypes(sql) {
  let s = sql;
  s = s.replace(/`/g, "");
  s = s.replace(/\bBIGINT\s+UNSIGNED\b/gi, "BIGINT");
  s = s.replace(/\bINT\s+UNSIGNED\b/gi, "INTEGER");
  s = s.replace(/\bTINYINT\s+UNSIGNED\b/gi, "SMALLINT");
  s = s.replace(/\bTINYINT\s*\(\s*1\s*\)/gi, "BOOLEAN");
  s = s.replace(/\bLONGTEXT\b/gi, "TEXT");
  s = s.replace(/\bMEDIUMTEXT\b/gi, "TEXT");
  s = s.replace(/\bDATETIME\b/gi, "TIMESTAMP");
  s = s.replace(/\bDOUBLE\b/gi, "DOUBLE PRECISION");
  s = s.replace(
    /\bgeo_point\s+POINT\s+NOT\s+NULL\s+SRID\s+4326\b/gi,
    "geo_point geography(POINT, 4326) NOT NULL",
  );
  s = s.replace(
    /\bST_SRID\s*\(\s*POINT\s*\(\s*([^)]+)\s*\)\s*,\s*4326\s*\)/gi,
    "ST_SetSRID(ST_MakePoint($1), 4326)::geography",
  );
  s = s.replace(
    /\b(\w+)\s+BIGINT\s+NOT\s+NULL\s+AUTO_INCREMENT\b/gi,
    "$1 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL",
  );
  s = s.replace(/\bAUTO_INCREMENT\b/gi, "GENERATED BY DEFAULT AS IDENTITY");
  s = s.replace(/\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP\b/gi, "");
  s = s.replace(/ENGINE\s*=\s*InnoDB[^;]*/gi, "");
  s = s.replace(/DEFAULT\s+CHARSET\s*=\s*\w+[^;]*/gi, "");
  s = s.replace(/COLLATE\s*=\s*\w+[^;,)']*/gi, "");
  s = s.replace(/CHARACTER\s+SET\s+\w+/gi, "");
  s = s.replace(
    /JSON_VALID\((\w+)\)/gi,
    "$1 IS NOT NULL",
  );
  s = s.replace(/SET\s+SESSION\s+unique_checks\s*=\s*\d+;?/gi, "");
  s = s.replace(/SET\s+NAMES\s+\w+;?/gi, "");
  s = s.replace(/\bFROM\s+DUAL\b/gi, "");
  s = s.replace(
    /DATE_ADD\s*\(\s*NOW\s*\(\s*\)\s*,\s*INTERVAL\s+(\d+)\s+(\w+)\s*\)/gi,
    (_, n, unit) => `(NOW() + INTERVAL '${n} ${unit.toLowerCase().replace(/s$/, "")}')`,
  );
  s = s.replace(/SET\s+time_zone\s*=[^;]+;?/gi, "");
  s = s.replace(/SET\s+FOREIGN_KEY_CHECKS\s*=\s*\d+;?/gi, "");
  s = s.replace(/DELIMITER\s+\$\$;?/gi, "");
  s = s.replace(/DELIMITER\s+;?;?/gi, "");
  s = s.replace(/\$\$/g, "");

  s = s.replace(/(\w+)\s+ENUM\(([^)]+)\)/gi, (_, col, values) => {
    return `${col} VARCHAR(64) CHECK (${col} IN (${values}))`;
  });

  s = s.replace(/DATE_SUB\s*\(\s*NOW\s*\(\s*\)\s*,\s*INTERVAL\s+(\d+)\s+(\w+)\s*\)/gi, (_, n, unit) => {
    const u = unit.toLowerCase().replace(/s$/, "");
    return `(NOW() - INTERVAL '${n} ${u}')`;
  });

  s = s.replace(/NOW\s*\(\s*\)\s*-\s*INTERVAL\s+(\d+)\s+(\w+)/gi, (_, n, unit) => {
    const u = unit.toUpperCase();
    const pgUnit = u === "DAY" ? "days" : u === "MINUTE" ? "minutes" : u === "HOUR" ? "hours" : u.toLowerCase();
    return `NOW() - INTERVAL '${n} ${pgUnit}'`;
  });

  return s;
}

function convertTableBlock(block) {
  const tableMatch = block.match(/CREATE\s+TABLE\s+(\w+)/i);
  if (!tableMatch) {
    return block;
  }
  const table = tableMatch[1];
  const indexes = [];
  let body = block;

  body = body.replace(/,\s*UNIQUE\s+KEY\s+(\w+)\s*\(([^)]+)\)/gi, ", CONSTRAINT $1 UNIQUE ($2)");
  body = body.replace(/,\s*UNIQUE\s+KEY\s*\(([^)]+)\)/gi, ", UNIQUE ($1)");

  body = body.replace(/,\s*SPATIAL\s+INDEX\s+(\w+)\s*\(([^)]+)\)/gi, () => "");
  body = body.replace(/,\s*KEY\s+(\w+)\s*\(([^)]+)\)/gi, (_, name, cols) => {
    indexes.push(`CREATE INDEX ${name} ON ${table} (${cols});`);
    return "";
  });

  const spatialMatch = block.match(/SPATIAL\s+INDEX\s+(\w+)\s*\(([^)]+)\)/i);
  if (spatialMatch) {
    indexes.push(
      `CREATE INDEX ${spatialMatch[1]} ON ${table} USING GIST (${spatialMatch[2]});`,
    );
  }

  body = body.replace(/,\s*\n\s*\)/g, "\n)");
  body = body.replace(/\)\s*;/g, ");\n");

  return `${body.trim()}\n${indexes.join("\n")}`.trim();
}

function convertSchemaSql(sql) {
  let s = convertTypes(sql);
  const parts = s.split(/(?=CREATE\s+TABLE\s+)/i);
  return parts.map((p) => (p.match(/^CREATE\s+TABLE/i) ? convertTableBlock(p) : p)).join("\n\n");
}

function convertViewExpressions(sql) {
  let s = sql;
  s = s.replace(
    /TIMESTAMPDIFF\s*\(\s*SECOND\s*,\s*([^,]+),\s*([^)]+)\)/gi,
    "EXTRACT(EPOCH FROM ($2 - $1))",
  );
  s = s.replace(
    /TIMESTAMPDIFF\s*\(\s*MINUTE\s*,\s*([^,]+),\s*([^)]+)\)/gi,
    "FLOOR(EXTRACT(EPOCH FROM ($2 - $1)) / 60)",
  );
  s = s.replace(/\bHOUR\s*\(\s*([^)]+)\)/gi, "EXTRACT(HOUR FROM $1)");
  s = s.replace(
    /DATE_SUB\s*\(\s*CURRENT_TIMESTAMP\s*,\s*INTERVAL\s+(\d+)\s+DAY\s*\)/gi,
    "(CURRENT_TIMESTAMP - INTERVAL '$1 days')",
  );
  return s;
}

function convertInserts(sql) {
  let s = sql.replace(/\bINSERT\s+IGNORE\s+INTO\b/gi, "INSERT INTO");

  s = s.replace(
    /ON\s+DUPLICATE\s+KEY\s+UPDATE\s+([\s\S]*?);/gi,
    (_, updates) => {
      const converted = updates
        .replace(/VALUES\s*\(\s*(\w+)\s*\)/gi, "EXCLUDED.$1")
        .trim();
      return `ON CONFLICT DO UPDATE SET ${converted};`;
    },
  );

  const parts = s.split(/(?=INSERT\s+INTO\s)/i);
  const out = [];
  for (const part of parts) {
    const stmt = part.trim();
    if (!stmt) continue;
    if (/^INSERT\s+INTO/i.test(stmt) && !/ON\s+CONFLICT/i.test(stmt)) {
      out.push(`${stmt.replace(/;\s*$/, "")} ON CONFLICT DO NOTHING;`);
    } else {
      out.push(stmt);
    }
  }
  s = out.join("\n\n");
  s = s.replace(/\)\s*;\s*ON CONFLICT/gi, ") ON CONFLICT");
  s = s.replace(
    /ON p\.code = v\.parent_code ON CONFLICT/gi,
    "ON p.code = v.parent_code\nON CONFLICT",
  );
  return s;
}

function convertSessionVariables(sql) {
  if (!/@\w+/.test(sql)) {
    return sql;
  }

  const varNames = new Map();
  let s = sql;

  s = s.replace(
    /SET\s+@(\w+)\s*=\s*\(([\s\S]*?)\)\s*;/gi,
    (_, name, expr) => {
      const pgName = `v_${name}`;
      varNames.set(name, pgName);
      const trimmed = expr.trim();
      if (/^SELECT\b/i.test(trimmed)) {
        return `${trimmed} INTO ${pgName};`;
      }
      return `SELECT (${trimmed}) INTO ${pgName};`;
    },
  );

  s = s.replace(
    /SET\s+@(\w+)\s*=\s*([^;]+);/gi,
    (_, name, expr) => {
      const pgName = `v_${name}`;
      varNames.set(name, pgName);
      let pgExpr = expr.trim();
      for (const [mysql, pg] of varNames) {
        pgExpr = pgExpr.replace(new RegExp(`@${mysql}\\b`, "g"), pg);
      }
      return `${pgName} := ${pgExpr};`;
    },
  );

  for (const [mysql, pg] of varNames) {
    s = s.replace(new RegExp(`@${mysql}\\b`, "g"), pg);
  }

  const declares = [...new Set(varNames.values())]
    .map((v) => `  ${v} BIGINT;`)
    .join("\n");

  return `DO $$
DECLARE
${declares}
BEGIN
${s
  .split("\n")
  .map((l) => (l.trim() ? `  ${l}` : ""))
  .filter(Boolean)
  .join("\n")}
END $$;`;
}

function splitTriggerBlocks(sql) {
  const blocks = [];
  const re = /CREATE\s+TRIGGER\s+/gi;
  const indices = [];
  let m;
  while ((m = re.exec(sql)) !== null) {
    indices.push(m.index);
  }
  for (let i = 0; i < indices.length; i++) {
    blocks.push(sql.slice(indices[i], indices[i + 1] ?? sql.length));
  }
  return blocks;
}

function findTriggerBodyEnd(block) {
  const beginIdx = block.search(/\bBEGIN\b/i);
  if (beginIdx === -1) return block.length;
  let depth = 0;
  const re = /\b(BEGIN|END\s+IF|END\s+LOOP|END)\b/gi;
  re.lastIndex = beginIdx;
  let m;
  while ((m = re.exec(block)) !== null) {
    const token = m[1].toUpperCase().replace(/\s.*/, "");
    if (token === "BEGIN") {
      depth++;
    } else if (token === "END" && !/^END\s+(IF|LOOP)/i.test(m[0])) {
      depth--;
      if (depth === 0) {
        return m.index + m[0].length;
      }
    }
  }
  return block.length;
}

function mysqlDeclareToPg(decl) {
  let d = decl.trim();
  d = d.replace(/\bBIGINT\s+UNSIGNED\b/gi, "BIGINT");
  d = d.replace(/\bBOOLEAN\s+DEFAULT\s+FALSE\b/gi, "BOOLEAN := FALSE");
  d = d.replace(/\bBIGINT\s+DEFAULT\s+NULL\b/gi, "BIGINT := NULL");
  return `  ${d};`;
}

function convertTriggerBlock(block) {
  const header = block.match(
    /CREATE\s+TRIGGER\s+(\w+)\s+(BEFORE|AFTER)\s+(INSERT|UPDATE(?:\s+OR\s+UPDATE)?|DELETE)\s+ON\s+(\w+)\s+FOR\s+EACH\s+ROW\s+BEGIN/i,
  );
  if (!header) return "";

  const [, name, timing, event, table] = header;
  const events = event.replace(/\s+OR\s+UPDATE/i, "").trim();
  const endIdx = findTriggerBodyEnd(block);
  let body = block.slice(block.indexOf("BEGIN") + 5, endIdx - 3);

  const declareLines = [];
  body = body.replace(/DECLARE\s+([^;]+);/gi, (_, decl) => {
    declareLines.push(mysqlDeclareToPg(decl));
    return "";
  });

  body = convertTypes(body);
  body = body.replace(
    /SIGNAL\s+SQLSTATE\s+'45000'\s+SET\s+MESSAGE_TEXT\s*=\s*'([^']+)'/gi,
    "RAISE EXCEPTION '$1'",
  );
  body = body.replace(
    /SET\s+@allow_(\w+)\s*=\s*TRUE\s*;/gi,
    "PERFORM set_config('niers.allow_$1', 'on', true);",
  );
  body = body.replace(
    /SET\s+@allow_(\w+)\s*=\s*FALSE\s*;/gi,
    "PERFORM set_config('niers.allow_$1', 'off', true);",
  );
  body = body.replace(
    /COALESCE\s*\(\s*@allow_(\w+)\s*,\s*FALSE\s*\)\s*=\s*FALSE/gi,
    "COALESCE(current_setting('niers.allow_$1', true), 'off') <> 'on'",
  );
  body = body.replace(
    /SET\s+NEW\.(\w+)\s*=\s*ST_SetSRID\(ST_MakePoint\(NEW\.longitude,\s*NEW\.latitude\),\s*4326\)::geography\s*;/gi,
    "NEW.$1 := ST_SetSRID(ST_MakePoint(NEW.longitude, NEW.latitude), 4326)::geography;",
  );

  const logic = body
    .split("\n")
    .map((l) => (l.trim() ? `  ${l.trim()}` : ""))
    .filter(Boolean)
    .join("\n");

  const declareSection =
    declareLines.length > 0 ? `DECLARE\n${declareLines.join("\n")}\n` : "";

  return `CREATE OR REPLACE FUNCTION ${name}_fn()
RETURNS TRIGGER AS $$
${declareSection}BEGIN
${logic}
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER ${name}
${timing} ${events} ON ${table}
FOR EACH ROW
EXECUTE FUNCTION ${name}_fn();
`;
}

function convertTriggersMysqlToPg(sql) {
  let s = sql.replace(/DELIMITER\s+\$\$;?/gi, "").replace(/DELIMITER\s+;?/gi, "").replace(/\$\$/g, "");
  const blocks = splitTriggerBlocks(s);
  return blocks.map(convertTriggerBlock).filter(Boolean).join("\n");
}

function buildUpdatedAtTriggers() {
  const tables = [
    "users",
    "user_profiles",
    "service_cases",
    "intake_reports",
    "emergency_incidents",
    "dispatches",
    "emergency_units",
    "disaster_events",
    "relief_requests",
    "facilities",
    "shelter_activations",
    "relief_hub_activations",
  ];
  const fn = `CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

`;
  const triggers = tables
    .map(
      (t) => `DROP TRIGGER IF EXISTS trg_${t}_updated_at ON ${t};
CREATE TRIGGER trg_${t}_updated_at
BEFORE UPDATE ON ${t}
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();
`,
    )
    .join("\n");
  return fn + triggers;
}

function processSchemaFile(filename) {
  const raw = readFileSync(join(MYSQL_DIR, filename), "utf8");
  return convertSchemaSql(raw);
}

function splitLargeUnionInserts(sql, batchSize = 400) {
  return sql.replace(
    /(INSERT INTO administrative_areas[\s\S]*?FROM\s*\(\s*)([\s\S]*?)(\)\s+AS\s+v[\s\S]*?;)/gi,
    (_, prefix, unionBody, suffix) => {
      const rows = unionBody.split(/\n\s*UNION ALL\s*\n/i);
      if (rows.length <= batchSize) {
        return `${prefix}${unionBody}${suffix}`;
      }
      const chunks = [];
      for (let i = 0; i < rows.length; i += batchSize) {
        const slice = rows.slice(i, i + batchSize).join("\n  UNION ALL\n  ");
        chunks.push(`${prefix}${slice}\n${suffix}`);
      }
      return chunks.join("\n\n");
    },
  );
}

function processSeedFile(filename) {
  const raw = readFileSync(join(MYSQL_DIR, filename), "utf8");
  let sql = convertTypes(raw);
  sql = convertViewExpressions(sql);
  sql = convertInserts(sql);
  if (filename === "22_seed_administrative_areas.sql") {
    sql = splitLargeUnionInserts(sql);
  }
  if (/@\w+/.test(sql)) {
    sql = convertSessionVariables(sql);
  }
  return sql;
}

function processViewsFile() {
  const raw = readFileSync(join(MYSQL_DIR, "20_views.sql"), "utf8");
  let sql = convertTypes(raw);
  sql = convertViewExpressions(sql);
  return sql;
}

function main() {
  const dirs = ["schema", "seeds", "migrations", "converted-sql", "notes", "scripts"];
  for (const d of dirs) {
    const p = join(OUT, d);
    if (!existsSync(p)) mkdirSync(p, { recursive: true });
  }

  const schemaParts = [PREAMBLE_PG, EXTENSIONS_PG];
  for (const f of SCHEMA_FILES) {
    schemaParts.push(`-- from ${f}\n${processSchemaFile(f)}`);
  }
  schemaParts.push(`-- from 27_alter (no-op)\n${ALTER_27_PG}`);
  const schemaSql = schemaParts.join("\n\n");
  writeFileSync(join(OUT, "schema", "001_schema.sql"), schemaSql);

  const triggersRaw = readFileSync(join(MYSQL_DIR, "19_triggers.sql"), "utf8");
  const triggersPg = convertTriggersMysqlToPg(triggersRaw);
  const updatedAt = buildUpdatedAtTriggers();
  writeFileSync(join(OUT, "schema", "002_triggers.sql"), `${updatedAt}\n\n${triggersPg}`);

  const viewsPg = processViewsFile();
  writeFileSync(join(OUT, "schema", "003_views.sql"), viewsPg);

  const seedParts = [];
  for (const f of SEED_FILES) {
    const converted = processSeedFile(f);
    writeFileSync(join(OUT, "converted-sql", f.replace(".sql", ".pg.sql")), converted);
    seedParts.push(`-- from ${f}\n${converted}`);
  }
  writeFileSync(join(OUT, "seeds", "004_seed_data.sql"), seedParts.join("\n\n"));

  for (const [src, dest] of [
    ["schema/001_schema.sql", "migrations/001_schema.sql"],
    ["schema/002_triggers.sql", "migrations/002_triggers.sql"],
    ["schema/003_views.sql", "migrations/003_views.sql"],
    ["seeds/004_seed_data.sql", "migrations/004_seed_data.sql"],
  ]) {
    writeFileSync(join(OUT, dest), readFileSync(join(OUT, src), "utf8"));
  }

  console.log("Conversion complete.");
}

main();
