CREATE TABLE administrative_areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    parent_area_id BIGINT NULL,
    area_type VARCHAR(64) CHECK (area_type IN ('division','district','upazila','union','ward','area')) NOT NULL,
    name VARCHAR(150) NOT NULL,
    code VARCHAR(80) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id), CONSTRAINT uq_administrative_areas_code UNIQUE (code), CONSTRAINT uq_administrative_areas_parent_type_name UNIQUE (parent_area_id, area_type, name),
    CONSTRAINT fk_administrative_areas_parent FOREIGN KEY (parent_area_id) REFERENCES administrative_areas(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_administrative_areas_name_not_blank CHECK (CHAR_LENGTH(TRIM(name)) > 0)
);
CREATE INDEX idx_administrative_areas_parent ON administrative_areas (parent_area_id);
CREATE INDEX idx_administrative_areas_type ON administrative_areas (area_type);

CREATE TABLE locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    public_uuid CHAR(36) NOT NULL,
    admin_area_id BIGINT NULL,
    latitude DECIMAL(9,6) NOT NULL,
    longitude DECIMAL(9,6) NOT NULL,
    geo_point geography(POINT, 4326) NOT NULL,
    address_text VARCHAR(255) NOT NULL,
    place_name VARCHAR(150) NULL,
    source VARCHAR(64) CHECK (source IN ('user_shared','dispatcher_selected','api_geocoded','manual_entry')) NOT NULL,
    created_by_user_id BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id), CONSTRAINT uq_locations_public_uuid UNIQUE (public_uuid),
    CONSTRAINT fk_locations_admin_area FOREIGN KEY (admin_area_id) REFERENCES administrative_areas(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_locations_created_by_user FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_locations_latitude CHECK (latitude BETWEEN -90.000000 AND 90.000000),
    CONSTRAINT chk_locations_longitude CHECK (longitude BETWEEN -180.000000 AND 180.000000),
    CONSTRAINT chk_locations_address_not_blank CHECK (CHAR_LENGTH(TRIM(address_text)) > 0)
);
CREATE INDEX idx_locations_admin_area ON locations (admin_area_id);
CREATE INDEX idx_locations_created_by ON locations (created_by_user_id);
CREATE INDEX idx_locations_lat_lng ON locations (latitude, longitude);
CREATE INDEX idx_locations_geo_point ON locations USING GIST (geo_point);

